// Writes the "Built with" section of README.md from src/scripts/libraries.js (same list as the "About" page),
// purpose texts, group titles and the closing credit line (about.madeWith) from the English language file. Replaces only the part between the markers
// <!-- libraries:start --> and <!-- libraries:end -->. Runs before every build (npm "prebuild").
import fs from 'node:fs';
import { RUNTIME, ASSETS, BUILD } from '../src/scripts/libraries.js';

const root = new URL('../', import.meta.url);
const readmeUrl = new URL('README.md', root);
const about = JSON.parse(fs.readFileSync(new URL('src/i18n/en_us.json', root), 'utf8')).about;

const cell = text => String(text).replace(/\|/g, '\\|');
const table = (title, items) => [
    `### ${title}`,
    '',
    '| Project | Used for | License |',
    '|---|---|---|',
    ...items.map(i => `| [${cell(i.name)}](${i.url}) | ${cell(about.libs[i.id] ?? '')} | ${cell(i.license)} |`),
    '',
].join('\n');

const section = [
    '<!-- libraries:start – generated by scripts/sync-readme.mjs from src/scripts/libraries.js, do not edit -->',
    cell(about.openSource),
    '',
    table(about.runtime, RUNTIME),
    table(about.assets, ASSETS),
    table(about.build, BUILD),
    '---',
    '',
    `<p align="center">${about.madeWith}</p>`,   // credit line of the "About" page, last line of the README
    '<!-- libraries:end -->',
].join('\n');

const readme = fs.readFileSync(readmeUrl, 'utf8');
const pattern = /<!-- libraries:start[\s\S]*?<!-- libraries:end -->/;
if (!pattern.test(readme)) throw new Error('README.md: markers <!-- libraries:start --> … <!-- libraries:end --> missing');
const updated = readme.replace(pattern, () => section);
if (updated !== readme) {
    fs.writeFileSync(readmeUrl, updated);
    console.log('README.md: "Built with" updated from libraries.js');
}
